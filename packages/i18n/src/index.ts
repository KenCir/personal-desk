export function relativeTime(value: string, now: string) {
  const seconds = (Date.parse(value) - Date.parse(now)) / 1000;
  if (Math.abs(seconds) < 60) return t('date.justNow');
  const formatter = new Intl.RelativeTimeFormat('ja-JP', { numeric: 'auto' });
  const unit = Math.abs(seconds) < 3600 ? 'minute' : Math.abs(seconds) < 86400 ? 'hour' : 'day';
  const divisor = unit === 'minute' ? 60 : unit === 'hour' ? 3600 : 86400;
  return formatter.format(Math.trunc(seconds / divisor), unit);
}
